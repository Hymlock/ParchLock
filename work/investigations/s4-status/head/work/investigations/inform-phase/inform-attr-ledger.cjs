// Inform attribute-source ledger (claude 2026-10-31, Inform phase P2). Reporting only.
// Per release Z title x profile key: where the live bit comes from (HEAD facts, not working copy).
//   N  = declared I6 name table names this key (D193 path)        F  = exact-digest attributeMap bit
//   0  = fact null / name missing (fail-closed)                    P  = PROFILE, layout proven in P1 packets
//   P? = PROFILE with no proof (open)
//                              -  = Glulx (separate track)
// node work/investigations/inform-phase/inform-attr-ledger.cjs -> inform-attr-ledger.md
const fs = require('fs'), path = require('path'), vm = require('vm'), cp = require('child_process');
const ROOT = path.join(__dirname, '../../..');
const inv = require(ROOT + '/work/investigations/zil-titles/grok-lane-1031/inform-plan/inventory.json');
const c = {}; vm.createContext(c); vm.runInContext(cp.execSync('git show HEAD:js/ModuleStatFactsClaude.js', { cwd: ROOT, maxBuffer: 1 << 26 }).toString('utf8'), c);
const FACTS = vm.runInContext('ModuleStatFactsClaude', c);
const KEYS = ['animate','absent','clothing','wearable','concealed','container','door','edible','enterable','female','general','light','lockable','locked','moved','on','open','openable','proper','scenery','scored','static','supporter','switchable','talkable','transparent','visited','workflag','worn','male','neuter','pluralname'];
// P1 proved PROFILE equal from light 9 up for the alphabetical layout (heist/library/break-in/...), and the
// shifted no-names rows map every key explicitly; so an unmapped key in a no-names row with a fact is P.
// Dialect tables that omit a name: bitFor returns null (grok GROK-REVIEW-p2-ledger-1450, live census).
const MISSING = { Heliopause: ['general','scored'], temple: ['male','neuter','pluralname'], Vacation: ['male','neuter'] };
const rows = (Array.isArray(inv) ? inv : inv.titles); const tally = {};
let md = '<!-- generated by inform-attr-ledger.cjs ' + new Date().toISOString() + ' -->\n# Inform attribute-source ledger (' + rows.length + ' release titles)\n\n';
md += 'N declared name | F fact bit | 0 fail-closed | P PROFILE (P1-proven layout) | P? PROFILE unproven | - Glulx\n\n';
md += '| Title | class | ' + KEYS.join(' | ') + ' |\n|' + '---|'.repeat(KEYS.length + 2) + '\n';
for (const r of rows) {
  const glulx = !/^z/.test(r.vm || ''); const f = FACTS[r.digest] || {}; const am = f.attributeMap || {};
  const cls = glulx ? 'glulx' : r.nameTable ? (r.stdOrder || 'names') : 'no-names';
  const named = new Set((r.names || r.declared || []).map(String));
  const cells = KEYS.map(k => {
    let v;
    if (glulx) v = '-';
    else if (r.digest === '1e206e79c42111a8c1fe07ea9abe050dbaa7726986afd9433b8f74c36b022079') v = '0'; // sutwin: no attribute bit set on any object (grok 1413) -> PROFILE can never read true
    else if (k === 'worn' && Number.isInteger(f.wornAttribute)) v = 'F';
    else if (Object.prototype.hasOwnProperty.call(am, k)) v = am[k] === null ? '0' : 'F';
    else if (r.nameTable) v = (MISSING[r.title] || MISSING[(r.file || '').split('.')[0]] || []).includes(k) ? '0' : 'N';
    else v = f.attributeMap ? 'P' : 'P?';
    tally[v] = (tally[v] || 0) + 1; return v; });
  md += '| ' + r.title + ' | ' + cls + ' | ' + cells.join(' | ') + ' |\n';
}
md += '\nTally: ' + JSON.stringify(tally) + '\n';
fs.writeFileSync(path.join(__dirname, 'inform-attr-ledger.md'), md); console.log(JSON.stringify(tally));
