// D283 public build helper.
//   node tools/public-games.js list
//       Regenerate release/public-games.txt from GAMES_INCLUDED.md (KEEP titles minus Glulx .gblorb).
//   node tools/public-games.js gamelist <listFile> <outGameList.js>
//       Write a GameList.js holding only the listed stories (menu shows only bundled games).
//       Per-game facts (ModuleStatFacts*.js etc.) are NOT filtered: knowledge for all titles ships,
//       so a story the player imports later is recognised by its digest (harness/import-recognition.js).
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.resolve(__dirname, '..');
const mode = process.argv[2];

function readList(file) {
  return fs.readFileSync(file, 'utf8').split(/\r?\n/).map(s => s.trim()).filter(s => s && s[0] !== '#');
}

if (mode === 'list') {
  const md = fs.readFileSync(path.join(root, 'GAMES_INCLUDED.md'), 'utf8');
  const files = [...new Set((md.match(/`games\/[^`]+\.js`/g) || []).map(s => s.slice(7, -1)))]
    .filter(f => !/\.gblorb\.js$/i.test(f)).sort();
  const missing = files.filter(f => !fs.existsSync(path.join(root, 'games', f)));
  if (missing.length) { console.error('ERROR: listed but not in games/: ' + missing.join(', ')); process.exit(1); }
  const out = ['# Public build story list (D283): GAMES_INCLUDED.md KEEP titles minus Glulx (.gblorb), one games/ filename per line.',
    '# Regenerate: node tools/public-games.js list. Used by build-android-public.bat via PARCHLOCK_GAMES_LIST.'].concat(files);
  fs.writeFileSync(path.join(root, 'release', 'public-games.txt'), out.join('\n') + '\n');
  console.log('release/public-games.txt: ' + files.length + ' stories');
} else if (mode === 'gamelist') {
  const listFile = process.argv[3], outFile = process.argv[4];
  if (!listFile || !outFile) { console.error('usage: gamelist <listFile> <outGameList.js>'); process.exit(2); }
  const keep = new Set(readList(listFile));
  const ctx = {}; vm.runInNewContext(fs.readFileSync(path.join(root, 'js', 'GameList.js'), 'utf8') + ';this.GL = GameList;', ctx);
  const kept = ctx.GL.filter(g => g && keep.has(g.Filename));
  const absent = [...keep].filter(f => !kept.some(g => g.Filename === f));
  if (absent.length) { console.error('ERROR: listed stories missing from js/GameList.js: ' + absent.join(', ')); process.exit(1); }
  const body = kept.map(g => '    ' + JSON.stringify(g, null, 4).replace(/\n/g, '\n    ')).join(',\n');
  fs.writeFileSync(outFile, '// Generated by tools/public-games.js for the public build (D283). Do not edit.\nvar GameList = [\n' + body + '\n];\n');
  console.log('GameList: ' + kept.length + ' of ' + ctx.GL.length + ' stories -> ' + outFile);
} else {
  console.error('usage: node tools/public-games.js list | gamelist <listFile> <outGameList.js>');
  process.exit(2);
}
